-- 1. CATÁLOGOS Y TABLAS MAESTRAS
CREATE TABLE ROL (
    ID_ROL NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    NOMBRE_ROL VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE TIPO_VEHICULO (
    ID_TIPO_VEHICULO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    NOMBRE_TIPO VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE ESTADO_BAHIA (
    ID_ESTADO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    NOMBRE_ESTADO VARCHAR2(50) NOT NULL UNIQUE
);

-- 2. USUARIOS Y VEHÍCULOS
CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    RUT VARCHAR2(12) NOT NULL UNIQUE,
    ID_DIRECTORIO_EXTERNO VARCHAR2(100), -- Para futura integración real
    NOMBRE_COMPLETO VARCHAR2(100) NOT NULL,
    EMAIL_INSTITUCIONAL VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD_PROTOTIPO VARCHAR2(255) NOT NULL, -- Campo exclusivo para evaluación, no es un campo final
    ID_ROL NUMBER NOT NULL,
    ESTADO_SINCRONIZACION VARCHAR2(20) DEFAULT 'VIGENTE' NOT NULL,
    FECHA_ULTIMO_ACCESO TIMESTAMP,
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL)
);

CREATE TABLE VEHICULO (
    ID_VEHICULO NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_TIPO_VEHICULO NUMBER NOT NULL,
    IDENTIFICADOR VARCHAR2(50), 
    CONSTRAINT FK_VEHICULO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_VEHICULO_TIPO FOREIGN KEY (ID_TIPO_VEHICULO) REFERENCES TIPO_VEHICULO(ID_TIPO_VEHICULO)
);

-- 3. INFRAESTRUCTURA FÍSICA Y HARDWARE (IoT)
CREATE TABLE BAHIA (
    ID_BAHIA NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    CODIGO_IOT VARCHAR2(50) NOT NULL UNIQUE, 
    UBICACION VARCHAR2(100) NOT NULL, 
    ID_ESTADO NUMBER NOT NULL,
    ID_TIPO_PERMITIDO NUMBER NOT NULL, 
    CONSTRAINT FK_BAHIA_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES ESTADO_BAHIA(ID_ESTADO),
    CONSTRAINT FK_BAHIA_TIPO FOREIGN KEY (ID_TIPO_PERMITIDO) REFERENCES TIPO_VEHICULO(ID_TIPO_VEHICULO)
);

CREATE TABLE DISPOSITIVO_IOT (
    ID_DISPOSITIVO NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_BAHIA NUMBER NOT NULL UNIQUE,
    DIRECCION_MAC VARCHAR2(20) NOT NULL UNIQUE,
    FIRMWARE_VERSION VARCHAR2(20),
    ESTADO_CONEXION VARCHAR2(20) DEFAULT 'OFFLINE' NOT NULL, 
    ULTIMO_PING TIMESTAMP,
    CONSTRAINT FK_IOT_BAHIA FOREIGN KEY (ID_BAHIA) REFERENCES BAHIA(ID_BAHIA)
);

-- 4. OPERACIONES CORE: RESERVAS Y TRANSACCIONES
CREATE TABLE RESERVA (
    ID_RESERVA NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_BAHIA NUMBER NOT NULL,
    FECHA_SOLICITUD TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    FECHA_EXPIRACION TIMESTAMP NOT NULL, 
    ESTADO_RESERVA VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL, 
    CONSTRAINT FK_RES_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_RES_BAHIA FOREIGN KEY (ID_BAHIA) REFERENCES BAHIA(ID_BAHIA)
);

CREATE TABLE TRANSACCION_USO (
    ID_TRANSACCION NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_RESERVA NUMBER NOT NULL, --Si o si con reserva (Modificación sprint 2)
    ID_USUARIO NUMBER NOT NULL,
    ID_BAHIA NUMBER NOT NULL,
    ID_VEHICULO NUMBER NOT NULL,
    FECHA_INICIO TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    FECHA_FIN TIMESTAMP,
    ESTADO_TRANSACCION VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL, 
    CONSTRAINT FK_TRANS_RESERVA FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
    CONSTRAINT FK_TRANS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_TRANS_BAHIA FOREIGN KEY (ID_BAHIA) REFERENCES BAHIA(ID_BAHIA),
    CONSTRAINT FK_TRANS_VEHICULO FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULO(ID_VEHICULO),
    CONSTRAINT CHK_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

-- 5. AUDITORÍA Y SOPORTE
CREATE TABLE LOG_EVENTO_IOT (
    ID_LOG NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_DISPOSITIVO NUMBER NOT NULL,
    TIPO_EVENTO VARCHAR2(50) NOT NULL, 
    PAYLOAD_RECIBIDO VARCHAR2(500), 
    FECHA_EVENTO TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT FK_LOG_IOT FOREIGN KEY (ID_DISPOSITIVO) REFERENCES DISPOSITIVO_IOT(ID_DISPOSITIVO)
);

CREATE TABLE TICKET_MANTENIMIENTO (
    ID_TICKET NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_BAHIA NUMBER NOT NULL,
    REPORTADO_POR NUMBER NOT NULL, 
    DESCRIPCION_FALLA VARCHAR2(255) NOT NULL,
    FECHA_REPORTE TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    FECHA_RESOLUCION TIMESTAMP,
    ESTADO_TICKET VARCHAR2(20) DEFAULT 'ABIERTO' NOT NULL, 
    CONSTRAINT FK_MANT_BAHIA FOREIGN KEY (ID_BAHIA) REFERENCES BAHIA(ID_BAHIA),
    CONSTRAINT FK_MANT_USUARIO FOREIGN KEY (REPORTADO_POR) REFERENCES USUARIO(ID_USUARIO)
);


-- SCRIPT DE ACTUALIZACIÓN (ALTER TABLES) - SPRINT 2


-- 1. Agregar estado (borrado lógico) a la tabla VEHICULO
ALTER TABLE VEHICULO ADD ESTADO_VEHICULO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL;

-- Agregar restricción (Check) para asegurar que solo reciba valores válidos
ALTER TABLE VEHICULO ADD CONSTRAINT CHK_ESTADO_VEHICULO CHECK (ESTADO_VEHICULO IN ('ACTIVO', 'INACTIVO'));

-- 2. Vincular el Vehículo a la Reserva
ALTER TABLE RESERVA ADD ID_VEHICULO NUMBER;

-- 3. Crear la llave foránea para mantener la integridad referencial
ALTER TABLE RESERVA ADD CONSTRAINT FK_RES_VEHICULO FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULO(ID_VEHICULO);

-- 4. Restringir los estados a los valores que usa el backend
ALTER TABLE USUARIO ADD CONSTRAINT CHK_ESTADO_USUARIO CHECK (ESTADO_SINCRONIZACION IN ('VIGENTE', 'BLOQUEADO', 'INACTIVO'));

ALTER TABLE RESERVA ADD CONSTRAINT CHK_ESTADO_RESERVA CHECK (ESTADO_RESERVA IN ('PENDIENTE', 'CONCRETADA', 'CANCELADA', 'EXPIRADA'));

ALTER TABLE TRANSACCION_USO ADD CONSTRAINT CHK_ESTADO_TRANSACCION CHECK (ESTADO_TRANSACCION IN ('ACTIVA', 'FINALIZADA'));

ALTER TABLE TICKET_MANTENIMIENTO ADD CONSTRAINT CHK_ESTADO_TICKET CHECK (ESTADO_TICKET IN ('ABIERTO', 'EN_REVISION', 'RESUELTO', 'ANULADO'));


-- CONTROL DE USO
-- Faltas por no llegar a la reserva, lista de espera y avisos dentro de la app.

-- 5. Faltas: una por cada reserva que vencio sin check-in.
--    Con 3 faltas VIGENTES el usuario no puede reservar. El administrador las anula para desbloquearlo.
CREATE TABLE FALTA_RESERVA (
    ID_FALTA NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_RESERVA NUMBER NOT NULL UNIQUE,
    FECHA_FALTA TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    ESTADO_FALTA VARCHAR2(20) DEFAULT 'VIGENTE' NOT NULL,
    FECHA_ANULACION TIMESTAMP,
    ANULADA_POR NUMBER,
    CONSTRAINT FK_FALTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_FALTA_RESERVA FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
    CONSTRAINT FK_FALTA_ADMIN FOREIGN KEY (ANULADA_POR) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT CHK_ESTADO_FALTA CHECK (ESTADO_FALTA IN ('VIGENTE', 'ANULADA'))
);

-- 6. Lista de espera: cuando no hay bahias libres para el tipo de vehiculo.
--    ESPERANDO -> OFRECIDA (se le guarda una bahia 15 min) -> CONFIRMADA (se crea la reserva)
--    Si no confirma queda VENCIDA y pasa el siguiente. CANCELADA = salio de la lista.
CREATE TABLE LISTA_ESPERA (
    ID_ESPERA NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_VEHICULO NUMBER NOT NULL,
    ID_TIPO_VEHICULO NUMBER NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    ESTADO_ESPERA VARCHAR2(20) DEFAULT 'ESPERANDO' NOT NULL,
    ID_BAHIA_OFRECIDA NUMBER,
    FECHA_OFERTA TIMESTAMP,
    FECHA_LIMITE_OFERTA TIMESTAMP,
    ID_RESERVA NUMBER,
    FECHA_CIERRE TIMESTAMP,
    CONSTRAINT FK_ESPERA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_ESPERA_VEHICULO FOREIGN KEY (ID_VEHICULO) REFERENCES VEHICULO(ID_VEHICULO),
    CONSTRAINT FK_ESPERA_TIPO FOREIGN KEY (ID_TIPO_VEHICULO) REFERENCES TIPO_VEHICULO(ID_TIPO_VEHICULO),
    CONSTRAINT FK_ESPERA_BAHIA FOREIGN KEY (ID_BAHIA_OFRECIDA) REFERENCES BAHIA(ID_BAHIA),
    CONSTRAINT FK_ESPERA_RESERVA FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
    CONSTRAINT CHK_ESTADO_ESPERA CHECK (ESTADO_ESPERA IN ('ESPERANDO', 'OFRECIDA', 'CONFIRMADA', 'VENCIDA', 'CANCELADA'))
);

-- 7. Avisos que el usuario ve dentro de la app (campana).
CREATE TABLE NOTIFICACION (
    ID_NOTIFICACION NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 NOCACHE ORDER) PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    MENSAJE VARCHAR2(300) NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LEIDA CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT FK_NOTIF_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT CHK_NOTIF_LEIDA CHECK (LEIDA IN ('S', 'N'))
);

-- Indices para las consultas que hace el backend cada 30 segundos
CREATE INDEX IDX_FALTA_USUARIO ON FALTA_RESERVA (ID_USUARIO, ESTADO_FALTA);
CREATE INDEX IDX_ESPERA_ESTADO ON LISTA_ESPERA (ESTADO_ESPERA, ID_TIPO_VEHICULO, FECHA_REGISTRO);
CREATE INDEX IDX_NOTIF_USUARIO ON NOTIFICACION (ID_USUARIO, LEIDA);
CREATE INDEX IDX_RESERVA_ESTADO ON RESERVA (ESTADO_RESERVA, FECHA_EXPIRACION);

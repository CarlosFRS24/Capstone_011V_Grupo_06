-- OMNIDOCK - PRUEBA DE LAS RESTRICCIONES CHECK
-- ==============================================================================

-- 0. LAS 6 RESTRICCIONES EXISTEN. Debe mostrar 6 filas, todas ENABLED
SELECT TABLE_NAME, CONSTRAINT_NAME, STATUS
  FROM USER_CONSTRAINTS
 WHERE CONSTRAINT_TYPE = 'C'
   AND CONSTRAINT_NAME LIKE 'CHK%'
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;

-- 1. USUARIO: estado que no existe. Debe fallar por CHK_ESTADO_USUARIO
UPDATE USUARIO SET ESTADO_SINCRONIZACION = 'SUSPENDIDO' WHERE ROWNUM = 1;

-- 2. VEHICULO: estado que no existe. Debe fallar por CHK_ESTADO_VEHICULO
UPDATE VEHICULO SET ESTADO_VEHICULO = 'ELIMINADO' WHERE ROWNUM = 1;

-- 3. VEHICULO nuevo con estado invalido (la restriccion tambien aplica al insertar).
--    Debe fallar por CHK_ESTADO_VEHICULO
INSERT INTO VEHICULO (ID_USUARIO, ID_TIPO_VEHICULO, IDENTIFICADOR, ESTADO_VEHICULO) VALUES (4, 1, 'Prueba CHECK', 'PERDIDO');

-- 4. RESERVA: estado que no existe. Debe fallar por CHK_ESTADO_RESERVA
UPDATE RESERVA SET ESTADO_RESERVA = 'ANULADA' WHERE ROWNUM = 1;

-- 5. TRANSACCION_USO: estado que no existe. Debe fallar por CHK_ESTADO_TRANSACCION
UPDATE TRANSACCION_USO SET ESTADO_TRANSACCION = 'PAUSADA' WHERE ROWNUM = 1;

-- 6. TRANSACCION_USO: fecha de fin anterior a la de inicio. Debe fallar por CHK_FECHAS
UPDATE TRANSACCION_USO SET FECHA_FIN = FECHA_INICIO - INTERVAL '1' HOUR WHERE FECHA_FIN IS NOT NULL AND ROWNUM = 1;

-- 7. TICKET_MANTENIMIENTO: estado que no existe. Debe fallar por CHK_ESTADO_TICKET
--    (el backend acepta "CERRADO" y lo guarda como RESUELTO; la base no lo acepta directo)
UPDATE TICKET_MANTENIMIENTO SET ESTADO_TICKET = 'CERRADO' WHERE ROWNUM = 1;

-- 8. NO QUEDO NADA GUARDADO. Debe mostrar 0 en las seis columnas
SELECT (SELECT COUNT(*) FROM USUARIO WHERE ESTADO_SINCRONIZACION = 'SUSPENDIDO') AS USUARIO,
       (SELECT COUNT(*) FROM VEHICULO WHERE ESTADO_VEHICULO IN ('ELIMINADO', 'PERDIDO')) AS VEHICULO,
       (SELECT COUNT(*) FROM RESERVA WHERE ESTADO_RESERVA = 'ANULADA') AS RESERVA,
       (SELECT COUNT(*) FROM TRANSACCION_USO WHERE ESTADO_TRANSACCION = 'PAUSADA') AS USO_ESTADO,
       (SELECT COUNT(*) FROM TRANSACCION_USO WHERE FECHA_FIN < FECHA_INICIO) AS USO_FECHAS,
       (SELECT COUNT(*) FROM TICKET_MANTENIMIENTO WHERE ESTADO_TICKET = 'CERRADO') AS TICKET
  FROM DUAL;

